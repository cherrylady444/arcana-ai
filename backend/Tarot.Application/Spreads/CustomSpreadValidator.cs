using Tarot.Domain;

namespace Tarot.Application.Spreads;

/// <summary>
/// Central trust boundary for AI-generated/custom spread structures.
/// Both recommendation output and reading creation pass through the same
/// validation rules so the browser cannot bypass AI-side constraints.
/// </summary>
public static class CustomSpreadValidator
{
    public const int MinPositions = 1;
    public const int MaxPositions = 10;
    public const int MaxNameLength = 100;
    public const int MaxDescriptionLength = 600;
    public const int MaxPositionTitleLength = 100;
    public const int MaxPositionPromptLength = 300;
    public const int MaxPositionDescriptionLength = 300;

    public static SpreadDefinition ValidateAndCreate(
        CustomSpreadDefinition customSpread,
        string key)
    {
        ArgumentNullException.ThrowIfNull(customSpread);

        var normalizedName = NormalizeRequired(
            customSpread.Name,
            nameof(customSpread.Name),
            MaxNameLength);

        var normalizedDescription = NormalizeRequired(
            customSpread.Description,
            nameof(customSpread.Description),
            MaxDescriptionLength);

        if (customSpread.Positions is null
            || customSpread.Positions.Count < MinPositions
            || customSpread.Positions.Count > MaxPositions)
        {
            throw new ArgumentException(
                $"A custom spread must contain between {MinPositions} and {MaxPositions} positions.",
                nameof(customSpread.Positions));
        }

        var orderedPositions = customSpread.Positions
            .OrderBy(position => position.Order)
            .ToArray();

        for (var index = 0; index < orderedPositions.Length; index++)
        {
            var expectedOrder = index + 1;
            var position = orderedPositions[index];

            if (position.Order != expectedOrder)
            {
                throw new ArgumentException(
                    "Custom spread position orders must be unique and sequential starting at 1.",
                    nameof(customSpread.Positions));
            }
        }

        var positions = orderedPositions
            .Select(position => new SpreadPositionDefinition(
                Order: position.Order,
                Key: $"position-{position.Order}",
                Title: NormalizeRequired(
                    position.Title,
                    nameof(position.Title),
                    MaxPositionTitleLength),
                Prompt: NormalizeRequired(
                    position.Prompt,
                    nameof(position.Prompt),
                    MaxPositionPromptLength),
                Description: NormalizeRequired(
                    position.Description,
                    nameof(position.Description),
                    MaxPositionDescriptionLength)))
            .ToArray();

        return new SpreadDefinition(
            Key: key,
            Name: normalizedName,
            ShortDescription: normalizedDescription,
            Description: normalizedDescription,
            Intent: "Situation-specific custom spread generated by Arcana.",
            Positions: positions,
            IsBuiltIn: false);
    }

    private static string NormalizeRequired(
        string? value,
        string parameterName,
        int maxLength)
    {
        var normalized = value?.Trim() ?? string.Empty;

        if (normalized.Length == 0)
        {
            throw new ArgumentException(
                $"{parameterName} is required.",
                parameterName);
        }

        if (normalized.Length > maxLength)
        {
            throw new ArgumentException(
                $"{parameterName} cannot exceed {maxLength} characters.",
                parameterName);
        }

        return normalized;
    }
}